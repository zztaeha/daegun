#!/usr/bin/env python3
# The Arabic presentation forms a font without Arabic layout is shaped through: each letter's contextual forms, and
# the lam-alef ligatures, the only ones Unicode makes obligatory (core spec, chapter 9.2).

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ucd

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "src", "daecore", "src", "daeshaper",
                   "generated", "arabic_fallback.rs")
FORMS = ["<initial>", "<medial>", "<final>", "<isolated>"]
# Lam with these alefs is unattested, so its ligature isn't obligatory (core spec, chapter 9.2).
UNATTESTED_ALEFS = range(0x0870, 0x0883)

def presentation_forms():
    single, double = {}, []
    with open(ucd.path("UnicodeData.txt"), encoding="utf-8") as f:
        for line in f:
            fields = line.split(";")
            tag, _, rest = fields[5].partition(" ")
            if tag not in FORMS:
                continue
            code, parts = int(fields[0], 16), [int(p, 16) for p in rest.split()]
            if len(parts) == 1:
                form = (parts[0], FORMS.index(tag))
                if form in single:
                    sys.exit("U+{:04X} and U+{:04X} are the same form".format(single[form], code))
                single[form] = code
            elif len(parts) == 2:
                double.append((code, tag, parts))
    return single, double

def main():
    single, double = presentation_forms()
    groups = {int(f[0], 16): f[3] for f in ucd.rows("ArabicShaping.txt")}
    letters = sorted({letter for letter, _ in single})
    first, last = letters[0], letters[-1]

    lam_alef = []
    for code, tag, (lam, alef) in double:
        if groups.get(lam) != "LAM" or groups.get(alef) != "ALEF" or alef in UNATTESTED_ALEFS:
            continue
        # After the contextual forms, an isolated lam-alef is an initial lam and a final alef; a final one, medial.
        lam_form = single[(lam, FORMS.index("<initial>" if tag == "<isolated>" else "<medial>"))]
        lam_alef.append((lam_form, single[(alef, FORMS.index("<final>"))], code))
    lam_alef.sort()
    if not lam_alef:
        sys.exit("no lam-alef ligatures found")

    out = [
        "// Generated by scripts/tools/gen/arabic-fallback.py from the Unicode Character Database {}.{}.{}. Do not"
        " edit.".format(*ucd.VERSION),
        "",
        "// The code the first row of `SHAPING` is for.",
        "pub(crate) const SHAPING_FIRST: u32 = 0x{:04X};".format(first),
        "",
        "// Each code's init, medi, fina and isol presentation forms, 0 for none.",
        "pub(crate) static SHAPING: [[u16; 4]; {}] = [".format(last - first + 1),
    ]
    for letter in range(first, last + 1):
        out.append("    [{}],".format(", ".join("0x{:04X}".format(single.get((letter, k), 0)) for k in range(4))))
    out += [
        "];",
        "",
        "// Each lam-alef ligature as the lam's form, the alef's form and the ligature, in code order.",
        "pub(crate) static LAM_ALEF: [[u16; 3]; {}] = [".format(len(lam_alef)),
    ]
    out += ["    [0x{:04X}, 0x{:04X}, 0x{:04X}],".format(*row) for row in lam_alef]
    out.append("];")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print("wrote {}".format(os.path.relpath(OUT)))

if __name__ == "__main__":
    main()
