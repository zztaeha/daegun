#!/usr/bin/env python3
# The OpenType language systems of BCP 47 language tags, from the OpenType language system tag registry, IANA's
# language subtag registry, ISO 639-3's code table and CLDR's likely subtags. Usage: language-tags.py [source folder]

import collections
import html
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "src/daecore/src/daeshaper/generated/language_tags.rs"
CLDR = "49.0.0"
SOURCES = {
    "languagetags.html": "https://learn.microsoft.com/en-us/typography/opentype/spec/languagetags",
    "language-subtag-registry": "https://www.iana.org/assignments/language-subtag-registry/language-subtag-registry",
    "iso-639-3.tab": "https://iso639-3.sil.org/sites/iso639-3/files/downloads/iso-639-3.tab",
    "likelySubtags.json": f"https://raw.githubusercontent.com/unicode-org/cldr-json/{CLDR}/cldr-json/cldr-core/"
                          "supplemental/likelySubtags.json",
}

HEADER = """\
// Generated by scripts/tools/gen/language-tags.py – do not edit.
// From the OpenType language system tag registry of {opentype}, the IANA language subtag registry of {iana} and
// CLDR {cldr}'s likely subtags.

use crate::daecore::daeshaper::ot::tag::Head::{{Any, Language, Prefix, Whole}};
use crate::daecore::daeshaper::ot::tag::Rule;

// Each two- or three-letter language subtag's tags in order of preference, sorted by subtag, two letters padded with
// a zero byte. A zero tag stands for none.
pub(crate) static LANGUAGE_TAGS: &[([u8; 3], [u8; 4]); {count}] = &[
"""

RULES = """\
];

// The least span after the first hyphen that an `Any` rule's subtags take.
pub(crate) const ANY_SPAN: usize = {span};

pub(crate) static TAG_RULES: &[Rule; {count}] = &[
"""

# Systems whose ISO 639 column lists other languages than their name does: the codes the name rules out ("*" for
# all) and the BCP 47 tags it names. Each quoted name is the registry's.
REFINED = {
    "APPH": ("*", ["und-fonnapa"]),  # "Phonetic transcription—Americanist conventions"
    "IPPH": ("*", ["und-fonipa"]),  # "Phonetic transcription—IPA conventions"
    "UPPH": ("*", ["und-fonupa"]),  # "Uralic Phonetic Alphabet"
    "SYRE": ("*", ["und-Syre"]),  # "Syriac, Estrangela script-variant (equivalent to ISO 15924 'Syre')"
    "SYRJ": ("*", ["und-Syrj"]),  # "Syriac, Western script-variant (equivalent to ISO 15924 'Syrj')"
    "SYRN": ("*", ["und-Syrn"]),  # "Syriac, Eastern script-variant (equivalent to ISO 15924 'Syrn')"
    "KGE": ("*", ["und-Geok"]),  # "Khutsuri Georgian", a script
    "PGR": ("*", ["el-polyton"]),  # "Polytonic Greek"
    "IRT": (["ga"], ["ga-Latg"]),  # "Irish Traditional", Irish in Gaelic type
    "MONT": ("*", ["mnw-TH"]),  # "Thailand Mon"
    "MOL": ([], ["ro-MD"]),  # "Moldavian": IANA retired mo for ro, Moldova's Romanian
    "PRO": ([], ["oc-provenc"]),  # "Provençal / Old Provençal"
    "NOR": ([], ["no"]),  # "Norwegian", listing Bokmål alone
    "QUZ": ("*", ["qu"]),  # "Quechua", listing Cusco's alone
    "MOR": ([], ["ary"]),  # "Moroccan": ISO 639-3's Moroccan Arabic
    "GAR": ([], ["ar-Syrc"]),  # "Garshuni", Arabic in Syriac script
    "ZHP": ("*", []),  # "Chinese, Phonetic", a transcription no language tag names
    "ZHS": ("*", []),  # The Chinese systems go by script and region, as `chinese` reads them.
    "ZHT": ("*", []),
    "ZHH": ("*", []),
    "ZHTM": ("*", []),
}
# Systems named for Quechua of one country, which take every Quechua language CLDR places there.
QUECHUA = {"QWH": "PE", "QVI": "EC", "QUH": "BO"}  # "Quechua (Peru)", "(Ecuador)", "(Bolivia)"


def part1_codes(path):
    rows = (line.split("\t") for line in path.read_text(encoding="utf-8").splitlines()[1:])
    codes = {row[0]: row[3] for row in rows if row[3]}
    # ISO 639-2 retired mol, mo's three-letter code, with mo in 2008; the registry still lists it.
    codes["mol"] = "mo"
    return codes


# Each system's tag, unpadded, with the language subtags its ISO 639 column lists (none for a note) and whether it's
# deprecated.
def read_registry(path, part1):
    text = path.read_text(encoding="utf-8")
    systems = {}
    for row in re.findall(r"<tr>(.*?)</tr>", text, re.S):
        cells = [html.unescape(c).strip() for c in re.findall(r"<td>(.*?)</td>", row, re.S)]
        if not cells:
            continue
        _, tag, column = cells
        parsed = re.fullmatch(r"'?([A-Z0-9]{2,4}) *'?( \(deprecated\))?", tag)
        assert parsed, tag
        codes = column.split("<")[0].replace(" ", "")
        codes = codes.split(",") if re.fullmatch(r"[a-z]{3}(,[a-z]{3})*", codes) else []
        systems[parsed[1]] = ({part1.get(c, c) for c in codes}, bool(parsed[2]))
    date = re.search(r'name="updated_at" content="(\d{4}-\d\d-\d\d)', text)[1]
    return date, systems


# IANA's records by type, then subtag (or whole tag for the grandfathered and redundant), each field's values listed.
def read_iana(path):
    blocks = path.read_text(encoding="utf-8").split("\n%%\n")
    records = collections.defaultdict(dict)
    for block in blocks[1:]:
        fields = collections.defaultdict(list)
        for line in block.splitlines():
            if line.startswith(" "):
                fields[name][-1] += " " + line.strip()
            else:
                name, _, value = line.partition(": ")
                fields[name].append(value)
        records[fields["Type"][0]][(fields["Subtag"] or fields["Tag"])[0]] = fields
    return re.match(r"File-Date: (\S+)", blocks[0])[1], records


# A retired record's replacement, the same language under its new code, or the codes it was split into.
def preferred(record):
    return record["Preferred-Value"][0] if record["Deprecated"] and record["Preferred-Value"] else None


def split(record):
    found = [re.fullmatch(r"see ((?:[a-z]{2,3}, )*[a-z]{2,3})", c) for c in record["Comments"]]
    return next((m[1].split(", ") for m in found if m), []) if record["Deprecated"] else []


class Languages:
    def __init__(self, systems, iana, likely):
        self.systems, self.iana, self.likely = systems, iana, likely
        self.named = collections.defaultdict(set)
        for tag, (codes, _) in systems.items():
            ruled_out, added = REFINED.get(tag, ([], []))
            for code in codes:
                if ruled_out != "*" and code not in ruled_out:
                    self.named[code].add(tag)
            for language in added:
                self.named[language].add(tag)
        # A macrolanguage and a code split into several are groups: each member falls back on the group's systems.
        records = iana["language"]
        self.groups = collections.defaultdict(list)
        self.members = collections.defaultdict(list)
        for code, record in records.items():
            for group in record["Macrolanguage"]:
                self.groups[code].append(group)
            for member in split(record):
                self.groups[member].append(code)
        # A code split into languages of one macrolanguage was of it too.
        for code, record in records.items():
            parts = [set(records[m]["Macrolanguage"]) for m in split(record) if m in records]
            common = set.intersection(*parts) if parts else set()
            self.groups[code] += sorted(common - set(self.groups[code]))
        for code, groups in self.groups.items():
            for group in groups:
                if not records.get(code, {}).get("Deprecated"):
                    self.members[group].append(code)
        self.renamed = {c: preferred(r) for c, r in records.items() if preferred(r)}
        self.renamed_from = collections.defaultdict(list)
        for old, new in self.renamed.items():
            self.renamed_from[new].append(old)
        for tag, region in QUECHUA.items():
            for member in self.members["qu"]:
                if self.likely.get(member, "").endswith("-" + region):
                    self.named[member].add(tag)
        self.chinese_languages = ["zh"] + self.members["zh"]
        self.found = {}

    # Fewer languages first, as a system named for fewer is the closer match; a deprecated one after the rest.
    def rank(self, tag):
        size = sum(tag in tags for tags in self.named.values())
        return self.systems[tag][1], size, tag

    def ranked(self, tags):
        return sorted(tags, key=self.rank)

    # Its own systems, then its new code's and its groups'. A group none names takes its members' when each has one;
    # a language none names, those of an old code the registry still lists.
    def tags(self, language):
        if language in self.found:
            return self.found[language]
        self.found[language] = []
        if language in self.chinese_languages:
            tags = self.chinese(language, None, None)
        else:
            tags = self.ranked(self.named[language])
        members = self.members.get(language)
        if not tags and members and all(self.named[m] for m in members):
            tags = self.ranked(set().union(*(self.named[m] for m in members)))
        if not tags:
            tags = self.ranked({t for old in self.renamed_from[language] for t in self.named[old]})
        wider = [self.renamed[language]] if language in self.renamed else []
        if language not in self.chinese_languages:
            wider += self.groups.get(language, [])
        for group in wider:
            tags += [t for t in self.tags(group) if t not in tags and not self.only_some(t, group, language)]
        self.found[language] = tags
        return tags

    # Whether `tag` names group `wider` alongside some, not all, of its members, and not `language`.
    def only_some(self, tag, wider, language):
        members = self.members.get(wider, [])
        named = {m for m in members if tag in self.named[m]}
        return bool(named) and len(named) < len(members) and language not in named

    # A tag with more than a language: its own systems, then its language's, dropping a subtag at a time (RFC 4647's
    # lookup).
    def complex(self, tag):
        tags = self.ranked(self.named[tag])
        wider = tag.rsplit("-", 1)[0]
        for t in self.complex(wider) if "-" in wider else self.tags(wider):
            if t not in tags:
                tags.append(t)
        return tags

    # CLDR's likely script and region for Chinese ("Add Likely Subtags"), a language CLDR doesn't list read as zh. A
    # language's likely script holds in its likely region; elsewhere a region writing Chinese in one script decides.
    def maximized(self, language, script, region):
        language = language if language in self.likely else "zh"
        own = self.likely[language]
        keys = [f"{language}-{script}-{region}", f"{language}-{region}", f"{language}-{script}"]
        keys = [k for k in keys if "None" not in k]
        if region and not own.endswith("-" + region):
            keys.append(f"und-{region}")
        found = next(self.likely[k] for k in keys + [language] if self.likely.get(k, "").startswith(("zh-", language)))
        _, likely_script, likely_region = found.split("-")
        return script or likely_script, region or likely_region

    # The registry's Chinese systems: Simplified, and Traditional with Hong Kong's and Macao's before the general.
    def chinese(self, language, script, region):
        script, region = self.maximized(language, script, region)
        if script == "Hans":
            return ["ZHS"]
        return {"HK": ["ZHH", "ZHT"], "MO": ["ZHTM", "ZHH", "ZHT"]}.get(region, ["ZHT"])

    # The regions that may change a Chinese language's systems: where CLDR places the language, or Chinese, in one.
    def chinese_regions(self, language):
        language = language if language in self.likely else "zh"
        keys = [k.split("-") for k in self.likely if re.fullmatch(f"(und|{language})(-[A-Z][a-z]{{3}})?-[A-Z]{{2}}", k)]
        own = {k[-1] for k in keys if k[0] == language}
        chinese = {k[1] for k in keys if k[0] == "und" and self.likely["-".join(k)].startswith("zh-")}
        return sorted(own | chinese)


def literal(tag):
    return "[0; 4]" if not tag else f'*b"{tag:<4}"'


def table(languages):
    codes = set(languages.iana["language"]) | set(languages.named) | set(languages.chinese_languages)
    rows = {}
    for language in sorted(c for c in codes if re.fullmatch("[a-z]{2,3}", c)):
        tags = languages.tags(language)
        # A three-letter subtag none names reads as its tag in capitals, so one whose capitals are another
        # language's system is held to none.
        if not tags and language.upper() in languages.systems:
            tags = [""]
        if tags and tags != [language.upper()]:
            rows[language] = tags
    return rows


# How the shaper reads a language tag (`ot/tag.rs`), for the generator to check its rules against: a grandfathered
# tag whole, then from its extended language subtag on, through the rules, then the table, then in capitals.
def read(tag, rows, rules, span):
    tag = tag.lower().replace("_", "-")
    if not tag or tag.startswith("x-"):
        return []
    singleton = next((i for i in range(1, len(tag) - 1) if tag[i - 1] == tag[i + 1] == "-"), None)
    limit = len(tag) if singleton is None else singleton - 1
    for head, value, subtags, tags in rules:
        if head == "Whole" and tag == value:
            return tags
    first = tag.split("-")
    if limit >= 6 and len(first) > 1 and re.fullmatch("[a-z]{3}", first[1]):
        cut = len(first[0]) + 1
        tag, limit = tag[cut:], limit - cut
    hyphen = tag.find("-")
    anywhere = 0 <= hyphen < limit and limit >= span + 2 and limit - hyphen >= span

    def has(subtag):
        return any(m.start() < limit and not tag[m.end():m.end() + 1].isalnum()
                   for m in re.finditer(re.escape(subtag), tag))

    for head, value, subtags, tags in rules:
        matched = {
            "Any": anywhere,
            "Whole": False,
            "Language": tag.startswith(value),
            "Prefix": limit >= len(value) and tag.startswith(value) and tag[len(value):len(value) + 1] in ("", "-"),
        }[head]
        if matched and all(has(s) for s in subtags):
            return tags
    language = tag.split("-")[0]
    if not re.fullmatch("[a-z]{2,3}", language):
        return []
    if language not in rows:
        return [language.upper()] if len(language) == 3 else []
    found = rows[language]
    return found[:found.index("")] if "" in found else found


# Each tag with more than a language subtag whose systems the table's reading wouldn't give: the registry's
# refinements and Chinese always, as a script must stand before a region, the rest where they differ.
def rules(languages, rows):
    iana = languages.iana
    forced, checked = {}, {}
    for _, added in REFINED.values():
        forced.update({tag: languages.complex(tag) for tag in added if "-" in tag})
    for language in languages.chinese_languages:
        forced[f"{language}-Hans"] = ["ZHS"]
        general = languages.chinese(language, "Hant", None)
        for region in languages.chinese_regions(language):
            if languages.chinese(language, "Hant", region) != general:
                forced[f"{language}-Hant-{region}"] = languages.chinese(language, "Hant", region)
        forced[f"{language}-Hant"] = general
        for region in languages.chinese_regions(language):
            if languages.chinese(language, None, region) != languages.tags(language):
                forced[f"{language}-{region}"] = languages.chinese(language, None, region)
    for variant, record in iana["variant"].items():
        for comment in record["Comments"]:
            same = re.fullmatch(r"Preferred tag is (\S+)", comment)
            if same and len(record["Prefix"]) == 1:
                checked[f"{record['Prefix'][0]}-{variant}"] = languages.complex(same[1]) if "-" in same[1] \
                    else languages.tags(same[1])
    for tag, record in list(iana["grandfathered"].items()) + list(iana["redundant"].items()):
        new = (record["Preferred-Value"] or [None])[0]
        if new:
            checked[tag] = languages.complex(new) if "-" in new else languages.tags(new)
        elif split(record):
            parts = [languages.tags(p) for p in split(record)]
            checked[tag] = sorted(set().union(*parts), key=languages.rank) if all(parts) else []
        else:
            checked[tag] = languages.complex(tag)

    real = lambda tags: [t for t in tags if t in languages.systems]
    wanted = dict(forced)
    wanted.update({t: tags for t, tags in checked.items() if real(tags) != real(read(t, rows, [], 0))})
    found = {tag: head(languages, tag) + (real(tags)[:3],) for tag, tags in wanted.items()}
    # A writing system any language may take decides before a variant of one language.
    anywhere = [found[t] for t in sorted((t for t in found if found[t][0] == "Any"),
                                         key=lambda t: (not t.startswith("und-"), found[t]))]
    found = list(found.values())
    whole = sorted(r for r in found if r[0] == "Whole")
    # Within a language, the longer prefix first, then the rule with more subtags.
    rest = sorted((r for r in found if r[0] in ("Prefix", "Language")),
                  key=lambda r: (r[1].split("-")[0], r[0] == "Language", -len(r[1]), -len(r[2]), r))
    out = anywhere + whole + rest
    span = min(sum(map(len, r[2])) for r in anywhere)
    for tag, tags in wanted.items():
        assert read(tag, rows, out, span) == real(tags)[:3], (tag, read(tag, rows, out, span), tags)
    return span, out, sorted(wanted)


# A rule's head and subtags for `tag`: any language for und and a variant with one prefix, the whole tag when
# grandfathered, else its language with its script and region, if any, as the prefix.
def head(languages, tag):
    lower = tag.lower()
    if tag in languages.iana["grandfathered"]:
        return "Whole", lower, []
    language, *rest = lower.split("-")
    script = next((s for s in rest if len(s) == 4 and s[0].isalpha()), None)
    region = next((s for s in rest if len(s) == 2 or len(s) == 3 and s.isdigit()), None)
    variants = [s for s in rest if s not in (script, region)]
    prefixes = [languages.iana["variant"].get(v, {}).get("Prefix", []) for v in variants]
    if language == "und" or variants and not script and not region and all(p == [language] for p in prefixes):
        return "Any", "", ["-" + s for s in rest]
    if script:
        return "Prefix", "-".join([language, script] + [region] * bool(region)), ["-" + v for v in variants]
    return "Language", language + "-", ["-" + s for s in [region] * bool(region) + variants]


def build(root):
    part1 = part1_codes(root / "iso-639-3.tab")
    opentype, systems = read_registry(root / "languagetags.html", part1)
    iana_date, iana = read_iana(root / "language-subtag-registry")
    likely = json.loads((root / "likelySubtags.json").read_text(encoding="utf-8"))["supplemental"]["likelySubtags"]
    languages = Languages(systems, iana, likely)
    rows = table(languages)
    span, found, wanted = rules(languages, rows)
    return (opentype, iana_date), rows, span, found, wanted


def main():
    root = Path(sys.argv[1] if len(sys.argv) > 1 else ROOT / "scripts/.out/langtags")
    missing = [n for n in SOURCES if not (root / n).exists()]
    if missing:
        raise SystemExit("\n".join([f"missing under {root}:"]
                                   + [f"    curl --create-dirs -o {root / n} '{SOURCES[n]}'" for n in missing]))
    (opentype, iana_date), rows, span, found, _ = build(root)
    text = HEADER.format(opentype=opentype, iana=iana_date, cldr=CLDR, count=sum(map(len, rows.values())))
    for language, tags in rows.items():
        key = language + "\\0" * (3 - len(language))
        text += "".join(f'    (*b"{key}", {literal(tag)}),\n' for tag in tags)
    text += RULES.format(span=span, count=len(found))
    for kind, value, subtags, tags in found:
        start = kind if kind == "Any" else f'{kind}("{value}")'
        listed = ", ".join(f'"{s}"' for s in subtags)
        tags = ", ".join(map(literal, tags))
        text += f"    Rule {{ head: {start}, subtags: &[{listed}], tags: &[{tags}] }},\n"
    OUT.write_text(text + "];\n", encoding="utf-8")
    print(f"{len(rows)} languages, {len(found)} rules -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
