def windows(path):
    xml = zipfile.ZipFile(path).read("word/document.xml").decode("utf-8")
    ids = {}
    for row in re.findall(r"<w:tr[ >].*?</w:tr>", xml, re.S):
        cells = [unescape("".join(re.findall(r"<w:t[^>]*>([^<]*)</w:t>", c))).strip()
                 for c in re.findall(r"<w:tc>.*?</w:tc>", row, re.S)]
        # A row's first tag, without the sort order some name after an underscore; rows that name none are skipped.
        tag = re.match(r"([A-Za-z]{2,3}(?:-[A-Za-z0-9]{1,8})*)(?:_\w+)?(?:,|$)", cells[1]) if len(cells) == 2 else None
        if tag and re.fullmatch(r"0x[0-9A-Fa-f]{4}", cells[0]):
            ids[int(cells[0], 16)] = tag.group(1)
    return ids


def mac(path):
    text = re.sub(r"<[^>]+>", " ", path.read_text(encoding="utf-8"))
    text = " ".join(unescape(text).split())
    table = text.split("Macintosh Language Codes", 1)[1].split("The Microsoft platform", 1)[0]
    codes = {int(code): name.strip() for code, name in re.findall(r"\b(\d{1,3}) ([^\d]+?)(?= \d{1,3} |$)", table)}
    assert set(codes.values()) == set(MAC), set(codes.values()) ^ set(MAC)
    return {code: MAC[name] for code, name in codes.items()}


def subtags(tag):
    # An extended language subtag stands for its own language: zh-yue is yue.
    first, *rest = tag.split("-")
    if rest and re.fullmatch(r"[A-Za-z]{3}", rest[0]):
        first, rest = rest[0], rest[1:]
    script = region = ""
    variants = []
    for part in rest:
        if len(part) == 4 and part.isalpha():
            script = part.title()
        elif (len(part) == 2 and part.isalpha()) or (len(part) == 3 and part.isdigit()):
            region = part.upper()
        else:
            variants.append(part.lower())
    return first.lower(), script, region, variants


# UTS #35's likely subtags: each missing subtag from the first entry that matches; a language without one as it is.
def likely(table, language, script, region):
    for trial in ((language, script, region), (language, "", region), (language, script, ""), (language, "", "")):
        found = table.get("-".join(p for p in trial if p))
        if found:
            _, s, r, _ = subtags(found)
            return language, script or s, region or r
    return language, script, region


# UTS #35's removal of likely subtags: the shortest of the language alone, with its region, or with its script that
# adds back to the same tag.
def shortened(table, tag):
    language, script, region, variants = subtags(tag)
    full = likely(table, language, script, region)
    for trial in ((language, "", ""), (language, "", region), (language, script, "")):
        if likely(table, *trial) == full:
            return "-".join([p for p in trial if p] + variants)
    return "-".join([p for p in full if p] + variants)


def rust(name, about, pairs):
    items = [f'(0x{code:04X}, "{tag}"),' for code, tag in sorted(pairs.items())]
    assert all(re.fullmatch(r"[A-Za-z0-9-]+", tag) for tag in pairs.values()), name
    return "\n".join([f"// {about}", f"pub(crate) static {name}: &[(u16, &str); {len(items)}] = &[",
                      *wrapped("    ", items), "];"])


def main():
    root = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else ROOT / "scripts/.out/name-languages")
    missing = [n for n in SOURCES if not (root / n).exists()]
    if missing:
        raise SystemExit("\n".join([f"missing under {root}:"]
                                   + [f"    curl --create-dirs -o {root / n} '{SOURCES[n]}'" for n in missing]))
    table = json.loads((root / "likelySubtags.json").read_text(encoding="utf-8"))["supplemental"]["likelySubtags"]
    win = {code: shortened(table, tag) for code, tag in windows(root / "ms-lcid.docx").items()}
    mac_codes = {code: shortened(table, tag) for code, tag in mac(root / "Chap6name.html").items()}
    body = HEADER + "\n" + rust("WINDOWS", "Each Windows language ID's tag, sorted by ID.", win)
    body += "\n\n" + rust("MAC", "Each Mac language code's tag, sorted by code.", mac_codes) + "\n"
    OUT.write_text(body, encoding="utf-8")
    print(f"wrote {OUT}: {len(win)} Windows IDs, {len(mac_codes)} Mac codes")


main()
