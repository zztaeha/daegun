#!/usr/bin/env python3
# Writes daemath/srgb/tables.rs: sRGB levels to linear light, and the thresholds and buckets that take
# linear light back to the nearest level. Exact against the sRGB curve in f64, checked as it is built.

import math
import pathlib
import struct

OUT = pathlib.Path(__file__).resolve().parents[3] / "src" / "daecore" / "src" / "daemachine" / "daemath" / "srgb" / "tables.rs"


def f32(x):
    return struct.unpack("<f", struct.pack("<f", x))[0]


def bits(x):
    return struct.unpack("<I", struct.pack("<f", x))[0]


def from_bits(b):
    return struct.unpack("<f", struct.pack("<I", b))[0]


def encode(v):
    s = 12.92 * v if v <= 0.0031308 else 1.055 * math.pow(v, 1 / 2.4) - 0.055
    return max(0, min(255, math.floor(s * 255 + 0.5)))


def decode(level):
    c = level / 255
    return c / 12.92 if c <= 0.04045 else math.pow((c + 0.055) / 1.055, 2.4)


ONE = bits(1.0)
LOW = bits(2.0 ** -12)

threshold = [0] * 257
for k in range(1, 256):
    lo, hi = 0, ONE
    while lo < hi:
        mid = (lo + hi) // 2
        if encode(from_bits(mid)) >= k:
            hi = mid
        else:
            lo = mid + 1
    threshold[k] = lo
threshold[256] = bits(float("inf"))
assert from_bits(threshold[2]) > 2.0 ** -12, "below LOW only levels 0 and 1 may occur"

step = []
for b in range((ONE - LOW) >> 15):
    lo = LOW + (b << 15)
    k0, k1 = encode(from_bits(lo)), encode(from_bits(lo + (1 << 15) - 1))
    assert k1 - k0 <= 1, f"bucket {b} crosses {k1 - k0} thresholds"
    step.append(k0)

linear = [bits(f32(decode(k))) for k in range(256)]
assert all(encode(from_bits(linear[k])) == k for k in range(256)), "a level does not come back"


def table(name, kind, values, fmt, per):
    lines = [f"pub(super) const {name}: [{kind}; {len(values)}] = ["]
    for i in range(0, len(values), per):
        lines.append("    " + " ".join(fmt(v) + "," for v in values[i:i + per]))
    lines.append("];")
    return "\n".join(lines)


OUT.write_text(
    "// Generated by scripts/tools/gen/srgb-tables.py; edit that, not this.\n\n"
    "// Each level's linear light, as f32 bits.\n"
    + table("LINEAR", "u32", linear, lambda v: f"0x{v:08x}", 8) + "\n\n"
    "// The least linear light, as f32 bits, that reaches each level; one past the last never does.\n"
    + table("THRESHOLD", "u32", threshold, lambda v: f"0x{v:08x}", 8) + "\n\n"
    f"// The level at the start of each bucket of 2^15 f32 values from 2^-12 up to 1.\n"
    + table("STEP", "u8", step, str, 24) + "\n"
)
print(f"wrote {OUT}: {len(step)} buckets")
