#!/usr/bin/env python3
# Writes daekit/cache/standard_latin.rs: the Adobe standard Latin set (PDF, Annex D.2) as code points, each character
# the four Latin encodings of Annex D name, through the Adobe Glyph List, less MacRoman's 15 Mac-only ones.

import pathlib
import sys

from fontTools import agl
from fontTools.encodings.MacRoman import MacRoman
from fontTools.encodings.StandardEncoding import StandardEncoding

OUT = pathlib.Path(__file__).resolve().parents[3] / "src" / "daecore" / "src" / "daekit" / "cache" / "standard_latin.rs"

MAC_ONLY = {
    "notequal", "infinity", "lessequal", "greaterequal", "partialdiff", "summation", "product", "pi",
    "integral", "Omega", "radical", "approxequal", "Delta", "lozenge", "apple",
}

# PDFDocEncoding (Annex D.3) where it is not ASCII or Latin-1: the accents at 0x18 to 0x1F, the 31 names at
# 0x80 to 0x9E, and the euro at 0xA0. 0xAD is unused.
PDFDOC_ACCENTS = ["breve", "caron", "circumflex", "dotaccent", "hungarumlaut", "ogonek", "ring", "tilde"]
PDFDOC_HIGH = [
    "bullet", "dagger", "daggerdbl", "ellipsis", "emdash", "endash", "florin", "fraction", "guilsinglleft",
    "guilsinglright", "minus", "perthousand", "quotedblbase", "quotedblleft", "quotedblright", "quoteleft",
    "quoteright", "quotesinglbase", "trademark", "fi", "fl", "Lslash", "OE", "Scaron", "Ydieresis", "Zcaron",
    "dotlessi", "lslash", "oe", "scaron", "zcaron",
]


def code_point(name):
    text = agl.toUnicode(name)
    if len(text) != 1:
        sys.exit(f"{name} is not one character through the AGL: {text!r}")
    return ord(text)


def main():
    if len(PDFDOC_HIGH) != 0x9F - 0x80:
        sys.exit(f"PDFDocEncoding's high names number {len(PDFDOC_HIGH)}, not 31")
    names = {n for n in StandardEncoding if n != ".notdef"}
    names |= {n for n in MacRoman[0x20:0x7F] + MacRoman[0x80:] if n != ".notdef" and n not in MAC_ONLY}
    names |= set(PDFDOC_ACCENTS) | set(PDFDOC_HIGH) | {"Euro"}
    points = {code_point(n) for n in names}
    # WinAnsiEncoding by its code page, 1252, whose 0xA0 and 0xAD are the no-break space and soft hyphen
    # Annex D's notes make of its second space and hyphen; PDFDocEncoding is Latin-1 from 0xA1, less 0xAD.
    for byte in range(0x20, 0x100):
        if byte == 0x7F:
            continue
        try:
            points.add(ord(bytes([byte]).decode("cp1252")))
        except UnicodeDecodeError:
            pass
        if byte >= 0xA1 and byte != 0xAD:
            points.add(byte)
    points |= set(range(0x20, 0x7F))

    for name in MAC_ONLY - {"apple"}:
        if code_point(name) in points:
            sys.exit(f"{name}, which Annex D leaves out, reached the set")
    if any(p > 0xFFFF for p in points):
        sys.exit("a code point past the BMP, which a u16 table can't hold")

    values = sorted(points)
    lines = [
        "// Generated by scripts/tools/gen/standard-latin.py. Do not edit.",
        "",
        "// The Adobe standard Latin character set (PDF, Annex D.2) as Unicode code points, ascending: what",
        "// StandardEncoding, MacRomanEncoding, WinAnsiEncoding and PDFDocEncoding encode, through the AGL.",
        f"pub(crate) const STANDARD_LATIN: [u16; {len(values)}] = [",
    ]
    row = "   "
    for v in values:
        lit = f" 0x{v:04X},"
        if len(row) + len(lit) > 99:
            lines.append(row)
            row = "   "
        row += lit
    lines.append(row)
    lines.append("];")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(values)} code points written to {OUT}")


if __name__ == "__main__":
    main()
