// Where OS/2 holds ulUnicodeRange1 to 4.
const UNICODE_RANGE: usize = 42;

// OS/2's ulUnicodeRange bits with only those a kept code point falls in left set, so a subset claims no range it
// dropped; bit 57 stays for any code point past the BMP.
pub(crate) fn prune_unicode_ranges(os2: &mut [u8], codes: impl Iterator<Item = u32>) {
    let mut kept = [0u32; 4];
    for cp in codes {
        let i = RANGES.partition_point(|&(_, last, _)| last < cp);
        if let Some(&(_, _, bit)) = RANGES.get(i).filter(|&&(first, ..)| first <= cp) {
            kept[usize::from(bit / 32)] |= 1 << (bit % 32);
        }
        if (0x1_0000..=0x11_0000).contains(&cp) {
            kept[1] |= 1 << 25;
        }
    }
    for (i, bits) in kept.into_iter().enumerate() {
        if let Some(stated) = read_u32_be(os2, UNICODE_RANGE + 4 * i) {
            write_u32_be(os2, UNICODE_RANGE + 4 * i, stated & bits);
        }
    }
}

